// ============================================================================
// IPoolable.cs
// ----------------------------------------------------------------------------
// GameObjectPool이 인스턴스를 꺼내줄 때(Get)와 되돌려받을 때(Release) 자동으로 호출해주는
// 선택적 콜백 인터페이스입니다. 구현은 필수가 아니며, 없으면 풀은 그냥 SetActive만 토글합니다.
// 재사용될 때 초기화가 필요한 상태가 있는 컴포넌트에서 구현하세요.
// 예) 데미지 텍스트라면 OnGetFromPool()에서 알파값을 1로 되돌리고, OnReleaseToPool()에서
//     진행 중이던 페이드/트윈 코루틴을 정리하는 식으로 활용할 수 있습니다. (HUD 쪽에서 재사용 예정)
// ============================================================================

public interface IPoolable
{
    /// <summary>풀에서 꺼내져 활성화된 직후 호출됩니다. 상태를 처음 상태로 리셋하세요.</summary>
    void OnGetFromPool();

    /// <summary>풀로 반납되어 비활성화되기 직전 호출됩니다. 진행 중이던 코루틴/트윈 등을 정리하세요.</summary>
    void OnReleaseToPool();
}